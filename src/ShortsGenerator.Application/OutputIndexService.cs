using System.Globalization;
using System.Text;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Logging.Abstractions;
using ShortsGenerator.Domain;

namespace ShortsGenerator.Application;

// Day 28: output/ holds one folder per job, named by its Guid - safe (Day 11), but unreadable
// in Explorer. output/INDEX.md lists every finished video by date and title, with its length,
// whether it has been reviewed, and links to the file and the folder.
public sealed class OutputIndexService
{
    private const int MaxVideos = 500;

    private readonly IVideoJobRepository _repository;
    private readonly IVideoPlanStore _planStore;
    private readonly IJobArtifactWriter _artifacts;
    private readonly IJobOutputLocator _locator;
    private readonly TimeProvider _timeProvider;
    private readonly ILogger<OutputIndexService> _logger;

    public OutputIndexService(
        IVideoJobRepository repository, IVideoPlanStore planStore, IJobArtifactWriter artifacts, IJobOutputLocator locator,
        TimeProvider timeProvider, ILogger<OutputIndexService>? logger = null)
    {
        _repository = repository;
        _planStore = planStore;
        _artifacts = artifacts;
        _locator = locator;
        _timeProvider = timeProvider;
        _logger = logger ?? NullLogger<OutputIndexService>.Instance;
    }

    // The index is a convenience: it must never fail the render or review that triggered it.
    public async Task UpdateBestEffortAsync(CancellationToken cancellationToken)
    {
        try
        {
            await _artifacts.WriteOutputIndexAsync(await BuildAsync(cancellationToken), cancellationToken);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or InvalidDataException)
        {
            _logger.LogWarning(ex, "Could not update output/INDEX.md");
        }
    }

    public async Task<string> BuildAsync(CancellationToken cancellationToken)
    {
        var reviews = new ReviewService(_repository, _artifacts, _locator, _timeProvider);
        var jobs = (await _repository.ListRecentAsync(MaxVideos, cancellationToken))
            .Where(j => j.Status is VideoJobStatus.Completed)
            .ToList();

        var sb = new StringBuilder();
        sb.AppendLine("# Videos");
        sb.AppendLine();
        sb.AppendLine("Finished videos, newest first. Generated by the app - edits here are overwritten.");
        sb.AppendLine("Nothing is uploaded automatically: \"Reviewed\" means you ticked the whole checklist for this exact render.");
        sb.AppendLine();
        sb.AppendLine("| Created | Title | Topic | Length | Reviewed | Video | Folder |");
        sb.AppendLine("|---|---|---|---|---|---|---|");
        foreach (var job in jobs)
        {
            VideoPlan? plan = null;
            try
            {
                plan = await _planStore.LoadAsync(job.Id, cancellationToken);
            }
            catch (InvalidDataException)
            {
                // A broken plan.json still gets its row; the dashboard shows the details.
            }

            var state = await reviews.LoadStateAsync(job.Id, cancellationToken);
            var reviewed = state?.ReviewedAt is not null && !reviews.IsStale(job.Id, state.VideoWrittenAt)
                ? "yes"
                : state?.ReviewedAt is not null ? "re-rendered since" : "no";
            var length = plan is null ? "?" : $"{plan.Scenes.Sum(s => s.DurationSeconds).ToString("0", CultureInfo.InvariantCulture)}s";
            sb.AppendLine(
                $"| {job.CreatedAt.ToLocalTime():yyyy-MM-dd HH:mm} | {Cell(plan?.Title)} | {Cell(job.Topic)} | {length} | {reviewed} " +
                $"| [final.mp4]({job.Id}/final.mp4) | [{job.Id.ToString()[..8]}]({job.Id}/) |");
        }

        if (jobs.Count == 0)
        {
            sb.AppendLine("| - | (no finished videos yet) | | | | | |");
        }

        return sb.ToString();
    }

    // Titles and topics come from the user and the LLM: a "|" or a newline would break the table.
    private static string Cell(string? text) =>
        string.IsNullOrWhiteSpace(text) ? "-" : text.Replace("|", "/").ReplaceLineEndings(" ").Trim();
}
